-- This version changes the database to exactly what you requested:
--   RSVP:    id, guest_name, created_at
--   Comments:id, guest_name, message, created_at
-- IDs are simple integers: 1, 2, 3, ...
-- Guests can submit, but cannot directly read/update/delete table rows.
--
-- IMPORTANT:
-- Because you already have data in the current database, run this file
-- in Supabase SQL Editor to migrate the existing tables without deleting
-- the submitted records.
